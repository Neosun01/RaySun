const I18N_KEY = 'ray-lang';

function currentLang() {
  const saved = localStorage.getItem(I18N_KEY);
  if (saved === 'en' || saved === 'zh') return saved;
  // Auto-detect from browser
  const bl = (navigator.language || 'en').toLowerCase();
  return bl.startsWith('zh') ? 'zh' : 'en';
}

function applyLang(lang) {
  const d = DICT[lang];
  if (!d) return;
  document.documentElement.lang = lang === 'zh' ? 'zh' : 'en';

  // text nodes
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (d[key] != null) el.textContent = d[key];
  });
  // attributes: data-i18n-attr="aria-label:key,title:key"
  document.querySelectorAll('[data-i18n-attr]').forEach(el => {
    const map = el.getAttribute('data-i18n-attr');
    map.split(',').forEach(pair => {
      const [attr, key] = pair.split(':').map(s => s.trim());
      if (attr && key && d[key] != null) el.setAttribute(attr, d[key]);
    });
  });

  // Toggle button pressed state
  document.querySelectorAll('.lang-toggle .seg').forEach(btn => {
    const on = btn.dataset.lang === lang;
    btn.classList.toggle('active', on);
    btn.setAttribute('aria-pressed', on ? 'true' : 'false');
  });

  // Re-render the timeline (year axis + detail card) so translated text applies
  if (typeof window.refreshDetail === 'function') window.refreshDetail();
  if (typeof window.renderProjects === 'function') window.renderProjects();

  localStorage.setItem(I18N_KEY, lang);
}

window.__i18n = { DICT, applyLang, currentLang };
